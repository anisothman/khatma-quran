create table if not exists public.participants (
  id bigint generated by default as identity primary key,
  name text not null unique,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.khatma_settings (
  id integer primary key default 1 check (id = 1),
  current_week integer not null default 1,
  current_hizb_1 integer not null default 1,
  current_hizb_2 integer not null default 2,
  updated_at timestamptz not null default now()
);

create table if not exists public.week_completions (
  id bigint generated by default as identity primary key,
  week_number integer not null,
  participant_id bigint not null references public.participants(id) on delete cascade,
  completed boolean not null default true,
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  unique (week_number, participant_id)
);

create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text unique,
  created_at timestamptz not null default now()
);

